"""Нужен ли ответ на реплику интервьюера.

question — вопрос или задание кандидату: отвечаем сразу;
context  — приветствие, реакция, рассказ о компании, проверка связи: только в память (контекст);
maybe    — непонятно: решает ИИ (модель отвечает «НЕТ», если это не вопрос — карточка не появится).
Фильтр мгновенный и бесплатный: регулярные выражения по русскому и английскому.
"""
from __future__ import annotations

import re

QUESTION, CONTEXT, MAYBE = "question", "context", "maybe"

# Явные формулировки вопросов и заданий
STRONG = re.compile(
    r"\b(что так\w+|что значит|что (будет|произойд[её]т|случится),? если|в ч[её]м (разница|отличи\w+|смысл|суть)|"
    r"чем отлича\w+|чем (плох|хорош)\w*|как работа\w+|как устроен\w*|как реализ\w+|"
    r"для чего (нужн\w+|использ\w+|примен\w+)|зачем (нужн\w+|использ\w+)|когда (нужно|стоит|лучше) использ\w+|"
    r"как (бы )?(ты|вы) (бы )?(сделал\w*|реализовал\w*|решил\w*|поступил\w*|спроектировал\w*|починил\w*|ускорил\w*|"
    r"оптимизировал\w*|объяснил\w*|понимаете|понимаешь|думаете|думаешь|относитесь|относишься|считаете|считаешь|"
    r"организовал\w*|тестировал\w*|делали|делал|решали|решал)|"
    r"что бы (ты|вы)|приходилось ли|доводилось ли|был ли (у (вас|тебя) )?опыт|есть ли (у (вас|тебя) )?опыт|"
    r"(какие|какой|какая|какое|каких)\b[^.?!]{0,40}?\b(есть|бывают|существуют|знаете|знаешь|используете|используешь|"
    r"применяете|применяешь|выбрали|выбрал|плюсы|минусы|преимущества|недостатки)|"
    r"следующий вопрос|(вопрос|тема|задача) (про|о|об|по)|давай(те)? (разбер[её]м|обсудим|поговорим о|перейд[её]м к)|"
    r"(^|[,.!?]\s*)а (если|что|как|почему|зачем|когда|где|какой|какие|сколько|чем|вот если))",
    re.I,
)
# Повелительное наклонение, обращённое к кандидату
TASK = re.compile(
    r"\b(расскажи(те)?|объясни(те)?|опиши(те)?|приведи(те)?|назови(те)?|сравни(те)?|перечисли(те)?|"
    r"напиши(те)?|реализуй(те)?|спроектируй(те)?|предложи(те)?|покажи(те)?|поясни(те)?|оцени(те)?|"
    r"разбери(те)?|реши(те)?|посчитай(те)?|представь(те)?|подумай(те)?|продолжи(те)?|уточни(те)?|"
    r"протестируй(те)?|проверь(те)?|составь(те)?|придумай(те)?|нарисуй(те)?|распиши(те)?|набросай(те)?|"
    r"воспроизведи(те)?|пройди(сь|тесь)|проведи(те)?|продумай(те)?)\b",
    re.I,
)
# Задание через инфинитив: «тебе нужно объяснить…», «попробуй составить…», «Мне объяснить полный путь…»
# (распознавание часто режет фразу: «Тебе нужно» | «Мне объяснить…»). После глагола нужно дополнение —
# вводная «Давай попробуем вот эту логику воспроизвести.» сама по себе ответа не запускает.
TASK_VERBS = (r"объяснить|рассказать|описать|написать|показать|придумать|протестировать|проверить|составить|"
              r"спроектировать|разобрать|воспроизвести|нарисовать|реализовать|посчитать|оценить|предложить|"
              r"перечислить|назвать|привести|сравнить|решить|сделать|найти|расписать|пройтись|провести|набросать|"
              r"продумать|объяснять|рассказывать")
TASK_INF = re.compile(
    rf"\b(тебе|вам|нужно|надо|необходимо|требуется|попробуй(те)?|попробуем|можешь|можете|сможешь|сможете|"
    rf"хочу,? чтобы (ты|вы)|(твоя|ваша) задача|задача)\b[^.?!]{{0,40}}?\b({TASK_VERBS})\b\s+[^\s.?!]",
    re.I,
)
TASK_START = re.compile(rf"^\W*((мне|нам)\s+)?({TASK_VERBS})\b\s+[^\s.?!]", re.I)
WH = re.compile(r"\b(что|чем|чего|как|какой|какая|какое|какие|каким|какими|каких|почему|зачем|когда|где|куда|"
                r"откуда|сколько|кто|кого|кому|ли|разве)\b", re.I)
EN_Q = re.compile(r"\b(what|why|how|when|where|which|who|explain|describe|tell me|walk me through|can you|could you|"
                  r"would you|do you|have you|did you|difference between|compare|implement|design)\b", re.I)
# Технические вопросы о связи — кандидат ответит сам
META = re.compile(r"\b(слышно|слышите|слышишь|видно|видите|видишь|экран\w*|связь|микрофон\w*|камер\w+|звук|интернет\w*|"
                  r"можно начинать|удобно (говорить|сейчас)|подключ\w+|расшар\w+|демонстрац\w+|can you hear|see my screen)\b",
                  re.I)
FILLER_WORDS = (r"привет\w*|здравствуй\w*|добрый (день|вечер)|доброе утро|алло|окей|ок|ага|угу|ммм*|э+|понятно|хорошо|"
                r"отлично|супер|класс|спасибо|ясно|да|нет|так|ну|итак|ладно|верно|правильно|интересно|good|ok|okay|"
                r"great|thanks|thank you|right|cool|nice|sure|yes|no")
FILLER = re.compile(rf"^((({FILLER_WORDS})[\s,.!…-]*)+)$", re.I)
# Рассказ интервьюера о компании/задаче — без вопроса это контекст
NARRATIVE = re.compile(r"\b(у нас|мы (используем|делаем|пишем|работаем|разрабатываем|ищем)|наша (команда|компания)|"
                       r"наш (проект|продукт|сервис)|я (работаю|занимаюсь|отвечаю)|меня зовут|компания занимается|"
                       r"we (use|are|build)|our (team|company|product))\b", re.I)


SENTENCE_END = re.compile(r"(?<=[.!?…])\s+")
# Короткое указание темы прямо перед вопросом — оставляем вместе с вопросом
TOPIC_LEAD = re.compile(r"\b(вопрос (про|о|об|по)|тема|теперь (про|о|об|по)|давай(те)? (про|о|об|по|поговорим|перейд[её]м)|"
                        r"поговорим (про|о|об)|перейд[её]м (к|на)|про (базы|тестирование|архитектур|алгоритм)|"
                        r"давай(те)? попробуем|попробуем (вот )?эт\w+)", re.I)


def extract_question(text: str) -> tuple[str, str]:
    """Из склеенной реплики оставляет сам вопрос: («вопрос», «остальное — фон»).

    «Подписывайся на канал. А теперь следующий момент. Какие существуют уровни тестирования?»
    → («Какие существуют уровни тестирования?», «Подписывайся на канал. А теперь следующий момент.»)
    """
    t = (text or "").strip()
    sents = [s.strip() for s in SENTENCE_END.split(t) if s.strip()]
    if len(sents) <= 1:
        return t, ""
    marks = [i for i, s in enumerate(sents) if s.endswith("?") or classify(s)[0] == QUESTION]
    if not marks:
        marks = [i for i, s in enumerate(sents) if classify(s)[0] == MAYBE]
    if not marks:
        return t, ""
    first, last = marks[0], marks[-1]
    if first > 0 and TOPIC_LEAD.search(sents[first - 1]) and len(sents[first - 1].split()) <= 12:
        first -= 1  # «Давайте про базы данных. Что такое индекс?» — тема нужна для смысла
    if not sents[last].endswith("?"):
        # задание, а не вопрос: следующие предложения — его условия («…путь изменения телефона. От нажатия
        # кнопки до отображения в кабинете») — оставляем вместе, пока не началась болтовня/проверка связи
        while last + 1 < len(sents) and not FILLER.match(sents[last + 1]) and not META.search(sents[last + 1]):
            last += 1
    focus = " ".join(sents[first:last + 1])
    rest = " ".join(sents[:first] + sents[last + 1:])
    return focus, rest


def classify(text: str) -> tuple[str, int]:
    t = (text or "").strip()
    words = re.findall(r"\w+", t)
    if not words:
        return CONTEXT, -9
    if FILLER.match(t) or (len(words) <= 2 and "?" not in t):
        return CONTEXT, -5
    strong, task = bool(STRONG.search(t)), bool(TASK.search(t))
    # «нужно объяснить…» — почти всегда задание, но бывает и рассказом: пусть уточнит модель (ответ «НЕТ»)
    soft_task = not task and bool(TASK_INF.search(t) or TASK_START.search(t))
    score = 0
    if "?" in t:
        score += 2
    if strong:
        score += 3
    if task:
        score += 3
    if soft_task:
        score += 2
    if WH.search(t):
        score += 1
    if EN_Q.search(t):
        score += 2
    if META.search(t) and not strong and not task:
        score -= 4
    if NARRATIVE.search(t) and "?" not in t and not task:
        score -= 2
    if score >= 3:
        return QUESTION, score
    if score <= 0:
        return CONTEXT, score
    return MAYBE, score
