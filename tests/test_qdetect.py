"""Определитель «вопрос / контекст / не уверен» и выделение вопроса из склеенной реплики.
Запуск: .venv/bin/python -m pytest -q tests/test_qdetect.py"""
import pytest

from app.qdetect import CONTEXT, MAYBE, QUESTION, classify, extract_question

ANSWER = {QUESTION, MAYBE}  # MAYBE тоже доходит до модели (она ответит или скажет «НЕТ»)


@pytest.mark.parametrize("text", [
    "Что такое регрессионное тестирование?",
    "Какие существуют уровни тестирования",
    "Расскажите про пирамиду тестирования",
    "Объясни разницу между PUT и PATCH",
    "Как бы вы протестировали лифт",
    "А если пользователь введёт пустую строку?",
    # задания через инфинитив (видео: фраза порезана распознаванием)
    "Мне объяснить полный путь изменения телефона пользователя. От нажатия кнопкой сохранить до отображения нового номера в личном кабинете",
    "Тебе нужно мне объяснить полный путь изменения телефона пользователя",
    "Нужно протестировать форму логина",
    "Попробуй составить чек-лист для корзины",
    "Распиши, что происходит после нажатия кнопки",
    "Пройдись по шагам, как будешь искать причину",
    "Протестируй вот эту ручку",
])
def test_answers(text):
    assert classify(text)[0] in ANSWER


@pytest.mark.parametrize("text", [
    "Тебе нужно",
    "Позиция.",
    "Здравствуйте!",
    "Окей, понятно, спасибо",
    "Меня слышно? Экран видно?",
    "В прошлом проекте проверял интеграцию между Front, Back, PostgreSQL и Kafka.",
    "Давай попробуем вот эту логику воспроизвести.",
    "У нас в команде пять тестировщиков, мы используем pytest и Allure.",
    "Нам надо будет проверить логи после релиза, у нас это обычно делает дежурный.",
])
def test_context(text):
    assert classify(text)[0] == CONTEXT


def test_task_keeps_lead_and_details():
    focus, rest = extract_question(
        "Давай попробуем вот эту логику воспроизвести. Тебе нужно мне объяснить полный путь изменения телефона "
        "пользователя. От нажатия кнопки сохранить до отображения нового номера в личном кабинете")
    assert focus.startswith("Давай попробуем") and focus.endswith("в личном кабинете") and not rest


def test_question_from_promo():
    focus, rest = extract_question(
        "Подписывайся на мою обучающую программу, там много полезного. Какие существуют уровни тестирования?")
    assert focus == "Какие существуют уровни тестирования?" and rest.startswith("Подписывайся")
