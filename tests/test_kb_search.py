@pytest.mark.parametrize("heard, expected", HITS)
def test_hit(heard, expected):
    assert expected in Q, f"нет в базе: {expected}"
    found = INDEX.match(heard)
    top = [(round(s, 2), i["q"]) for s, i in INDEX.search(heard, 3)]
    assert found and found["q"] == expected, top


@pytest.mark.parametrize("heard", MISSES)
def test_miss(heard):
    found = INDEX.match(heard)
    top = [(round(s, 2), i["q"]) for s, i in INDEX.search(heard, 2)]
    assert found is None, top
